def upsert_pages():
    with sqlite3.connect(DB_PATH) as conn:
        cur = conn.cursor()
        for page in PAGES:
            existing = cur.execute("SELECT id FROM pages WHERE slug = ?", (page["slug"],)).fetchone()
            if existing:
                cur.execute(
                    "UPDATE pages SET title = ?, content = ?, parent = ?, link = ? WHERE id = ?",
                    (page["title"], page["content"], page["parent"], page["link"], existing[0]),
                )
            else:
                cur.execute(
                    "INSERT INTO pages (slug, title, content, parent, link) VALUES (?, ?, ?, ?, ?)",
                    (page["slug"], page["title"], page["content"], page["parent"], page["link"]),
                )


