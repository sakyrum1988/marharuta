def page_html(title, intro, badge, en_path, sections, links, faqs, note=None):
    parts = [SHARED_STYLE, '<section class="rucmp">']
    parts.append(
        f'<div class="rucmp-hero"><div class="rucmp-badge">{badge}</div><h1>{title}</h1>'
        f'<p>{intro}</p><div class="rucmp-switch"><a class="primary" href="{en_path}">Read In English</a>'
        '<a class="ghost" href="/ru/compare/">Все Сравнения На Русском</a></div></div>'
    )
    if note:
        parts.append(f'<div class="rucmp-note"><strong>Важно:</strong> {note}</div>')
    for section in sections:
        if section.get("kind") == "cards":
            parts.append('<div class="rucmp-grid">')
            for card in section["items"]:
                parts.append(f'<article class="rucmp-card"><h3>{card["title"]}</h3><p>{card["text"]}</p></article>')
            parts.append("</div>")
            continue
        parts.append('<section class="rucmp-section">')
        parts.append(f'<h2>{section["title"]}</h2>')
        for para in section.get("paragraphs", []):
            parts.append(f"<p>{para}</p>")
        if section.get("bullets"):
            parts.append('<ul class="rucmp-list">')
            for bullet in section["bullets"]:
                parts.append(f"<li>{bullet}</li>")
            parts.append("</ul>")
        parts.append("</section>")
    if links:
        parts.append('<section class="rucmp-section"><h2>Что посмотреть дальше</h2><div class="rucmp-links">')
        for link in links:
            parts.append(f'<a class="rucmp-link" href="{link[0]}"><h3>{link[1]}</h3><p>{link[2]}</p></a>')
        parts.append("</div></section>")
    if faqs:
        parts.append('<section class="rucmp-section rucmp-faq"><h2>Частые вопросы</h2>')
        for question, answer in faqs:
            parts.append(f"<details><summary>{question}</summary><p>{answer}</p></details>")
        parts.append("</section>")
    parts.append("</section>")
    return "".join(parts)


